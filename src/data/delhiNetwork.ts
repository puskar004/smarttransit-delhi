export function segmentIdFor(fromStopId: string, toStopId: string): string {
  return `${fromStopId}__${toStopId}`;
}

function buildDirectedSegments(): RoadSegment[] {
  const segments: RoadSegment[] = [];

  for (const link of UNDIRECTED_LINKS) {
    const stopA = STOP_BY_ID[link.a];
    const stopB = STOP_BY_ID[link.b];
    if (!stopA || !stopB) {
      throw new Error(`Invalid stop in link ${link.a} <-> ${link.b}`);
    }

    const fwdWaypoints: LatLng[] = [
      { lat: stopA.lat, lng: stopA.lng },
      ...(link.midPoints ?? []),
      { lat: stopB.lat, lng: stopB.lng },
    ];
    const revWaypoints = [...fwdWaypoints].reverse();
    const len = Math.max(350, Math.round(polylineLengthMeters(fwdWaypoints)));

    segments.push({
      id: segmentIdFor(link.a, link.b),
      fromStopId: link.a,
      toStopId: link.b,
      corridorName: link.corridorName,
      shortLabel: `${stopA.name} → ${stopB.name}`,
      waypoints: fwdWaypoints,
      lengthMeters: len,
      freeFlowSpeedKmh: link.freeFlowSpeedKmh,
      scheduledSpeedKmh: link.scheduledSpeedKmh,
      signalCount: link.signalCount,
      diurnalFactor: link.diurnal,
      upstreamSegmentIds: [],
    });

    segments.push({
      id: segmentIdFor(link.b, link.a),
      fromStopId: link.b,
      toStopId: link.a,
      corridorName: link.corridorName,
      shortLabel: `${stopB.name} → ${stopA.name}`,
      waypoints: revWaypoints,
      lengthMeters: len,
      freeFlowSpeedKmh: link.freeFlowSpeedKmh,
      scheduledSpeedKmh: link.scheduledSpeedKmh,
      signalCount: link.signalCount,
      diurnalFactor: link.diurnal,
      upstreamSegmentIds: [],
    });
  }

  // Populate upstreamSegmentIds (segments ending at this segment's fromStopId, excluding U-turn)
  const incomingByStop = new Map<string, RoadSegment[]>();
  for (const seg of segments) {
    const list = incomingByStop.get(seg.toStopId) ?? [];
    list.push(seg);
    incomingByStop.set(seg.toStopId, list);
  }

  for (const seg of segments) {
    const incoming = incomingByStop.get(seg.fromStopId) ?? [];
    seg.upstreamSegmentIds = incoming
      .filter((inc) => inc.fromStopId !== seg.toStopId)
      .map((inc) => inc.id);
  }

  return segments;
}

